export type AppLanguage = 'fa' | 'ar' | 'en';

export function formatDigits(value: string | number, lang: string = 'fa'): string {
  const str = String(value);
  if (lang === 'en') {
    // Convert Persian/Arabic digits to English ASCII
    return str
      .replace(/[۰٠]/g, '0')
      .replace(/[۱١]/g, '1')
      .replace(/[۲٢]/g, '2')
      .replace(/[۳٣]/g, '3')
      .replace(/[۴٤]/g, '4')
      .replace(/[۵٥]/g, '5')
      .replace(/[۶٦]/g, '6')
      .replace(/[۷٧]/g, '7')
      .replace(/[۸٨]/g, '8')
      .replace(/[۹٩]/g, '9');
  }

  const faDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  const arDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  const targetDigits = lang === 'ar' ? arDigits : faDigits;

  // Convert ASCII and cross-language digits to target language digits
  return str.replace(/[0-9۰-۹٠-٩]/g, (w) => {
    let num = -1;
    if (w >= '0' && w <= '9') num = w.charCodeAt(0) - 48;
    else {
      const faIdx = '۰۱۲۳۴۵۶۷۸۹'.indexOf(w);
      if (faIdx !== -1) num = faIdx;
      else {
        const arIdx = '٠١٢٣٤٥٦٧٨٩'.indexOf(w);
        if (arIdx !== -1) num = arIdx;
      }
    }
    return num !== -1 ? targetDigits[num] : w;
  });
}

